/**
 * The block vocabulary and the plain-text renderer belong to `emailBlocks.tsx`, which the editor, the
 * canvas and this sheet all read. This file re-exports them rather than restating them: a second
 * `blockLabel` is a second answer to what a block is called, and a second text renderer is how two
 * parts of the same message come to carry different facts.
 */
