/**
 * The kit behind the send sheet and the document import.
 *
 * Both screens are about one thing — a message leaving the building — and both need the same four
 * things from it: the API contract (`/api/email/*`), the vocabulary of a block, the attachment
 * rules, and a way to say *what could not be read* rather than drawing a blank.
 *
 * ── The block vocabulary is not defined here ────────────────────────────────────────────────────────
 *
 * `EmailBlock` comes from `@C7NTAX/shared`, because the editor, the renderer and the importer must
 * agree about what a block is or a block one of them draws silently disappears from a customer's
 * email. **There is deliberately no second renderer here.** The HTML and the text of a message come
 * from `POST /api/email/preview`, so the message a person approves in this sheet is literally the
 * message that goes out; this file only *describes* blocks (a label, one line of what it carries,
 * where it came from) for the lists the sheet draws.
 *
 * ── Degrading honestly ─────────────────────────────────────────────────────────────────────────────
 *
 * The Email API is part of the same change and may not be deployed on an instance this screen is
 * opened against. Every call therefore returns a discriminated result and every failure is rendered
 * by `CallNote`, which names the endpoint and repeats the API's own words. Nothing here invents a
 * friendlier message, and nothing renders a preview it did not receive.
 */
