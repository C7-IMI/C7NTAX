/** A call that did not answer, described well enough to be shown to a person. */
export interface CallFailure {
  /** The route, with its leading slash, as it appears in this file. */
  endpoint: string;
  status?: number;
  /** The API's own words when it sent any, otherwise a plain statement of what happened. */
  reason: string;
  /** Set when the failure is "this route is not on this instance" rather than a refusal. */
  absent: boolean;
}

function statusOf(error: unknown): number | undefined {
  return isAxiosError(error) ? error.response?.status : undefined;
}

export function describeFailure(endpoint: string, error: unknown): CallFailure {
  const status = statusOf(error);
  const reason = status === 404
    ? `${endpoint} is not on this instance`
    : apiErrorMessage(error, status ? `${endpoint} answered ${status}` : `${endpoint} could not be reached`);
  return { endpoint, status, reason, absent: status === 404 || status === 501 };
}

/** The API answers `{ … }` or `{ data: … }`; both are in use, so both are accepted. */
export function unwrap<T>(payload: unknown): T {
  if (payload && typeof payload === "object" && "data" in payload) {
    return (payload as { data: T }).data;
  }
  return payload as T;
}

// ── The preview, exactly as `POST /api/email/preview` returns it ─────────────

export interface EmailPreview {
  subject: string;
  html: string;
  /** The plain-text part that will be sent beside the HTML — what a client shows when it strips HTML. */
  text: string;
  /**
   * The text derived from the blocks. It is always present so the sheet can show both, and warn when
   * they carry different facts: a message read in a client that strips HTML has to be the same message.
   */
  derivedText: string;
  warnings: string[];
}

export type PreviewState =
  | { status: "loading" }
  | { status: "ready"; preview: EmailPreview }
  | { status: "failed"; failure: CallFailure };

/** Reads the preview response defensively: a field the API did not send is not invented here. */
export function readPreview(payload: unknown): EmailPreview | null {
  const body = unwrap<Record<string, unknown>>(payload);
  if (!body || typeof body !== "object") return null;
  const html = typeof body.html === "string" ? body.html : "";
  if (!html) return null;
  const text = typeof body.text === "string" ? body.text : "";
  const derivedText = typeof body.derivedText === "string" ? body.derivedText : text;
  return {
    subject: typeof body.subject === "string" ? body.subject : "",
    html,
    text,
    derivedText,
    warnings: Array.isArray(body.warnings) ? body.warnings.filter((w): w is string => typeof w === "string") : [],
  };
}

